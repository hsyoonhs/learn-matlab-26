clear, clc

%% 스칼라 연산
3 * 5

%% 스칼라-벡터 연산
(1:5) * 5

%% 벡터 연산
% (1:5) * (1:5)를 시도하면 아래의 오류 출력

% 행렬 곱셈의 차원이 잘못되었습니다. 첫 번째 행렬의 열 개수가 두 번째 행렬의 행 개수와 일치하는지 확인하십시오.
% 행렬의 각 요소에 대해 개별적으로 연산을 수행하려면 요소별 곱셈 연산에 TIMES(.*)를 사용하십시오.

(1:5) .* (1:5)

%% meshgrid(x, y)
% 2개의 벡터를 입력받아 2개의 2차원 행렬로 출력

[new_x, new_y] = meshgrid((1:5), (1:3))

% x, y에 대한 모든 경우의 곱셈 연산
new_x .* new_y