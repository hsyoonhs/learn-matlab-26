%% 예제 3.1
% 클라우지우스-클라페롱 방정식으로 주어진 온도에서 물의 포화수증기 압력 산출

%% 변수 정의

TempF = [-60:10:120];          % 온도 행렬 정의 (단위: F), -60에서 120까지 10만큼 증가
TempK = (TempF + 459.6) / 1.8; % 온도 단위를 절대온도(K)로 변환
Delta_H = 2.45e6;              % 2.453은 러프하게 2.45로 사용
R_air = 461;

%% 수증기압 계산

Vapor_Pressure = 6.11 * exp((Delta_H / R_air) * ((1 / 273) - (1 ./ TempK))); % 배열 나눗셈(./) 연산자

%% 결과 출력

my_results = [TempF', Vapor_Pressure'] % 작은따옴표(') 연산자로 행렬의 행과 열 맞바꿈(transpose)